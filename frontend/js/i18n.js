// The single source of truth for every selectable language. Adding one means
// exactly two things: an entry here plus a dictionary in `translations` above.
// `code` is what we store (settings, localStorage); `locale` is the BCP-47 tag
// for Intl/toLocale* formatting. They differ where the code is not a valid
// language tag — 'ch' is Swiss German, but "ch" alone is a country, not a
// language, so it must never be handed to Intl directly.
export const LANGUAGES = [
  { code: 'de', label: 'Deutsch',         locale: 'de-DE' },
  { code: 'ch', label: 'Schwiizerdütsch', locale: 'de-CH' },
  { code: 'en', label: 'English',         locale: 'en-GB' },
  { code: 'fr', label: 'Français',        locale: 'fr-FR' },
  { code: 'it', label: 'Italiano',        locale: 'it-IT' },
  { code: 'nl', label: 'Nederlands',      locale: 'nl-NL' },
  { code: 'da', label: 'Dansk',           locale: 'da-DK' },
  { code: 'no', label: 'Norsk',           locale: 'nb-NO' },
  { code: 'sv', label: 'Svenska',         locale: 'sv-SE' },
  { code: 'fi', label: 'Suomi',           locale: 'fi-FI' },
];

const DEFAULT_LANG = 'de';
// A key missing from the active language is looked up here before we give up.
// English first: for a Finnish or Danish user an English label beats a German one.
const FALLBACK_CHAIN = ['en', DEFAULT_LANG];

const LANG_BY_CODE = new Map(LANGUAGES.map(l => [l.code, l]));

/** True for a code that is both registered and actually translated. */
export function isLang(code) { return LANG_BY_CODE.has(code) && !!translations[code]; }

let currentLang = (() => {
  try { const l = localStorage.getItem('lang'); return isLang(l) ? l : DEFAULT_LANG; } catch (_) { return DEFAULT_LANG; }
})();

export function getLang() { return currentLang; }

/** BCP-47 tag for date/time formatting — pass this to Intl, never getLang(). */
export function getLocale() {
  return (LANG_BY_CODE.get(currentLang) ?? LANG_BY_CODE.get(DEFAULT_LANG)).locale;
}

export function setLang(lang) {
  currentLang = isLang(lang) ? lang : DEFAULT_LANG;
  document.documentElement.lang = getLocale();
  try { localStorage.setItem('lang', currentLang); } catch (_) {}
  applyLang();
}

/** Active language, then the fallback chain. undefined if nobody defines the key. */
function lookup(key) {
  const dict = translations[currentLang];
  if (dict && dict[key] !== undefined) return dict[key];
  for (const code of FALLBACK_CHAIN) {
    const d = translations[code];
    if (d && d[key] !== undefined) return d[key];
  }
  return undefined;
}

export function t(key, vars = {}) {
  const val = lookup(key);
  if (val === undefined) return key;
  if (typeof val !== 'string') return val;
  return val.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Look up a translation but return null if the key is undefined everywhere.
// Lets callers fall back to the existing HTML default rather than displaying
// the raw key.
function tOrNull(key) {
  const val = lookup(key);
  return typeof val === 'string' ? val : null;
}

export function applyLang() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = tOrNull(el.dataset.i18n);
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = tOrNull(el.dataset.i18nPh);
    if (v != null) el.placeholder = v;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const v = tOrNull(el.dataset.i18nTitle);
    if (v != null) el.title = v;
  });
}
